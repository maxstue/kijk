// Writes every HTTP operation of the OpenAPI document as a runtime list; the web BFF relays only these operations.
import { readFile, writeFile } from 'node:fs/promises';

const [input, output] = process.argv.slice(2);
const methods = new Set(['get', 'put', 'post', 'delete', 'patch', 'head', 'options']);
const spec = JSON.parse(await readFile(input, 'utf8'));
const operations = Object.entries(spec.paths)
  .map(([path, item]) => [path, Object.keys(item).filter((key) => methods.has(key))])
  .filter(([, pathMethods]) => pathMethods.length > 0);

await writeFile(
  output,
  `// Generated by @kijk/openapi-codegen from the API's OpenAPI document. Do not edit.
import type { paths } from './kijk';

/** HTTP operations by path template, as declared in the OpenAPI document. */
export const apiOperations = ${JSON.stringify(Object.fromEntries(operations))} as const satisfies Partial<Record<keyof paths, readonly string[]>>;
`,
);
