using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Kijk.Api.SourceGenerators;

/// <summary>
/// Generates compile-time dependency-injection registrations for the FluentValidation validators of the application layer.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ValidatorRegistrationGenerator : IIncrementalGenerator
{
    // Validators are registered by the compilation that defines the application module contract.
    private const string ApplicationModuleMetadataName = "Kijk.Application.IModule";
    private const string ValidatorBaseMetadataName = "FluentValidation.AbstractValidator`1";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var validators = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                static (syntaxContext, cancellationToken) => GetValidator(syntaxContext, cancellationToken))
            .Where(static validator => validator is not null)
            .Select(static (validator, _) => validator!);

        context.RegisterSourceOutput(
            validators.Collect().Combine(context.CompilationProvider),
            static (sourceContext, input) =>
            {
                if (GeneratorUtilities.IsDefiningCompilation(input.Right, ApplicationModuleMetadataName))
                {
                    Execute(sourceContext, input.Left);
                }
            });
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<ValidatorRegistration> candidates)
    {
        var registrations = new List<ValidatorRegistration>(candidates.Length);
        var validatorsByRequest = new Dictionary<ITypeSymbol, INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var orderedCandidates = candidates
            .GroupBy(static candidate => candidate.Validator, SymbolEqualityComparer.Default)
            .Select(static group => group.First())
            .OrderBy(static candidate => candidate.Validator.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), StringComparer.Ordinal);

        foreach (var candidate in orderedCandidates)
        {
            if (GeneratorUtilities.ReportGenericType(context, candidate.Validator))
            {
                continue;
            }

            if (validatorsByRequest.TryGetValue(candidate.Request, out var existing))
            {
                // The validation filter resolves a single IValidator<T>, so a second validator would silently replace the first.
                context.ReportDiagnostic(Diagnostic.Create(
                    GeneratorDiagnostics.DuplicateValidator,
                    candidate.Validator.Locations.FirstOrDefault(),
                    candidate.Request.Name,
                    existing.Name,
                    candidate.Validator.Name));
                continue;
            }

            validatorsByRequest.Add(candidate.Request, candidate.Validator);
            registrations.Add(candidate);
        }

        context.AddSource("GeneratedValidatorRegistrations.g.cs", SourceText.From(Render(registrations), Encoding.UTF8));
    }

    private static ValidatorRegistration? GetValidator(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        var validatorBase = context.SemanticModel.Compilation.GetTypeByMetadataName(ValidatorBaseMetadataName);
        var declaration = (ClassDeclarationSyntax)context.Node;
        if (validatorBase is null
            || context.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken) is not INamedTypeSymbol { IsAbstract: false } validator)
        {
            return null;
        }

        for (var type = validator.BaseType; type is not null; type = type.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, validatorBase))
            {
                return new ValidatorRegistration(validator, type.TypeArguments[0]);
            }
        }

        return null;
    }

    private static string Render(IReadOnlyCollection<ValidatorRegistration> registrations)
    {
        var source = new StringBuilder(
            """
            // <auto-generated />
            #nullable enable

            namespace Kijk.Application;

            internal static class GeneratedValidatorRegistrations
            {
                internal static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddValidators(
                    this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                {

            """);

        foreach (var registration in registrations)
        {
            source.Append("        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<global::FluentValidation.IValidator<")
                .Append(registration.Request.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .Append(">, ")
                .Append(registration.Validator.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .AppendLine(">(services);");
        }

        return source.AppendLine("        return services;")
            .AppendLine("    }")
            .AppendLine("}")
            .ToString();
    }

    private sealed class ValidatorRegistration(INamedTypeSymbol validator, ITypeSymbol request)
    {
        public INamedTypeSymbol Validator { get; } = validator;

        public ITypeSymbol Request { get; } = request;
    }
}